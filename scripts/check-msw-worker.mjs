#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const workerPath = 'public/mockServiceWorker.js';
const worker = readFileSync(workerPath, 'utf8');
const workerVersion = worker.match(/const PACKAGE_VERSION = '([^']+)'/)?.[1];
const packageVersion = JSON.parse(
  readFileSync('node_modules/msw/package.json', 'utf8'),
).version;

if (!workerVersion) {
  console.error(`Could not read PACKAGE_VERSION from ${workerPath}.`);
  process.exit(1);
}

if (workerVersion !== packageVersion) {
  console.error(
    [
      `MSW worker is ${workerVersion}, but the installed msw package is ${packageVersion}.`,
      'Run `npx msw init public/ --save` and commit the worker with the dependency update.',
    ].join('\n'),
  );
  process.exit(1);
}

const temporaryDirectory = mkdtempSync(join(tmpdir(), 'polyexam-msw-'));
const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';

try {
  execFileSync(npx, ['--no-install', 'msw', 'init', temporaryDirectory], {
    stdio: ['ignore', 'pipe', 'pipe'],
  });

  const expected = readFileSync(
    join(temporaryDirectory, 'mockServiceWorker.js'),
    'utf8',
  );

  if (expected !== worker) {
    console.error(
      [
        `${workerPath} is not the worker generated by msw ${packageVersion}.`,
        'Run `npx msw init public/ --save` and commit the result.',
      ].join('\n'),
    );
    process.exit(1);
  }
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}

console.log(`MSW worker matches msw ${packageVersion}.`);
